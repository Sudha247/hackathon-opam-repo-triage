(* Print an OCaml module with the digest of the files given on the command line. *)
let () =
  let files =
    List.sort
      (fun a b -> compare (Filename.basename a) (Filename.basename b))
      (List.tl (Array.to_list Sys.argv))
  in
  let ctx =
    List.fold_left
      (fun ctx f ->
        Digestif.SHA256.feed_string ctx
          (In_channel.with_open_bin f In_channel.input_all))
      Digestif.SHA256.empty files
  in
  Printf.printf "(* Generated by version/gen.ml. *)\nlet digest = %S\n"
    (String.sub Digestif.SHA256.(to_hex (get ctx)) 0 12)
